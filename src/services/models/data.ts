function tokenRates(
  image: { input: string; cachedInput: string; output: string },
  text?: { input: string; cachedInput: string; output?: string },
) {
  return {
    standard: { image, ...(text ? { text } : {}) },
    batch: {
      image: {
        input: (Number.parseFloat(image.input) / 2).toFixed(3),
        cachedInput: (Number.parseFloat(image.cachedInput) / 2).toFixed(3),
        output: (Number.parseFloat(image.output) / 2).toFixed(3),
      },
      ...(text
        ? {
            text: {
              input: (Number.parseFloat(text.input) / 2).toFixed(3),
              cachedInput: (Number.parseFloat(text.cachedInput) / 2).toFixed(3),
              ...(text.output
                ? { output: (Number.parseFloat(text.output) / 2).toFixed(3) }
                : {}),
            },
          }
        : {}),
    },
  };
}

